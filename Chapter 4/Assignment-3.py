marks=int(input("Enter your marks out off 100 i will tell your grade:"))

if marks>=90:
    print("Your Grade is A")
elif marks>=80:
    print("Your Grade is B")
elif marks>=70:
    print("Your Grade is C")
elif marks>=60:
    print("Your Grade is D")
elif marks>=40:
    print("Your Grade is F")
else:
    print("You are Fail")